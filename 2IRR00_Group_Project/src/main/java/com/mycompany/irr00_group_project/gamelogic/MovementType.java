/**
 * Enums representing the moves a tetris piece can perform.
 *
 * @author Jayson Leander, Yingyao Feng
 */
public enum MovementType {
    /** Move piece to the left. */
    LEFT,
    
    /** Move piece to the right. */
    RIGHT,
    
    /** Move piece down. */
    DOWN,
    
    /** Rotate piece. */
    ROTATE
}
